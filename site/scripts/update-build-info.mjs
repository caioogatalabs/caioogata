import { execSync } from 'child_process'
import { writeFileSync } from 'fs'
import { join, dirname } from 'path'
import { fileURLToPath } from 'url'

const __dirname = dirname(fileURLToPath(import.meta.url))
const root = join(__dirname, '..')

// Total commits on the current branch. Deliberately the same basis the V1 site
// used (v1 has 91 commits and shipped as 1.1.91), so the V1 and V2 stamps sit
// on one scale and can be compared against whatever is live.
let count = 1
try {
  count = parseInt(execSync('git rev-list --count HEAD', { encoding: 'utf8' }).trim(), 10) || 1
} catch {
  // not in a git repo or git unavailable — keep the fallback
}

const content = `// Auto-generated by scripts/update-build-info.mjs — do not edit manually\nexport const COMMIT_COUNT = ${count}\n`
writeFileSync(join(root, 'src/lib/build-info.ts'), content)
console.log(`[build-info] COMMIT_COUNT = ${count}`)
